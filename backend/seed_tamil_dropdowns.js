async function seedTamil() {
  try {
    for (const [category, values] of Object.entries(TAMIL_OPTIONS)) {
      const res = await pool.query('SELECT COUNT(*) as count FROM dropdown_options WHERE category = $1', [category]);
      const count = res.rows[0].count;
      
      if (count == 0) {
        console.log(`Seeding ${category} options (${values.length} items)...`);
        let order = 1;
        for (const val of values) {
          await pool.query(
            'INSERT INTO dropdown_options (id, category, value, display_order) VALUES ($1, $2, $3, $4)',
            [uuidv4(), category, val, order++]
          );
        }
      } else {
        console.log(`${category} already has ${count} items. Skipping.`);
      }
    }
    console.log('Tamil dropdown seeding complete.');
    process.exit(0);
  } catch (err) {
    console.error('Error seeding tamil dropdowns:', err);
    process.exit(1);
  }
}

seedTamil();
